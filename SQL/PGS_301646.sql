/*
 * 문제: 특정 형질을 가지는 대장균 찾기
 * 링크: https://school.programmers.co.kr/learn/courses/30/lessons/301646
 * DB: MySQL
 *
 * [문제 요약]
 * ECOLI_DATA 테이블에서 2번 형질을 보유하지 않으면서 1번이나 3번 형질을 보유한 대장균 개체의 수(COUNT)를 출력한다.
 * 1번과 3번을 모두 보유한 경우도 포함한다.
 *
 * [핵심 포인트]
 * 1. GENOTYPE은 2진수의 각 자리가 형질 하나를 의미한다. (오른쪽부터 1번, 2번, 3번, 4번)
 *    -> 자리 값: 1번 = 1(0001), 2번 = 2(0010), 3번 = 4(0100), 4번 = 8(1000)
 * 2. 비트 AND(&)는 두 수를 2진수로 겹쳐서 "둘 다 1인 자리"만 남긴다.
 *    -> GENOTYPE & 2 = 0 이면 2번 형질이 없다.
 * 3. 1번이나 3번은 마스크 하나로 한 번에 검사한다. 번호가 아니라 "자리 값"을 더해야 한다.
 *    -> 1 + 4 = 5 (0101), GENOTYPE & 5 > 0 이면 1번이나 3번 중 하나 이상 보유.
 *    -> 번호를 그대로 더해 1 + 3 = 4로 쓰면 3번 형질만 검사하게 되어 틀린다.
 * 4. AND/OR를 함께 쓰면 우선순위가 꼬일 수 있으므로 각 조건을 괄호로 묶는다.
 * 5. 출력 컬럼명이 COUNT여야 하므로 COUNT(*) AS COUNT로 별칭을 붙인다.
 */

SELECT COUNT(*) AS COUNT
FROM ECOLI_DATA
WHERE (GENOTYPE & 2) = 0   -- 2번 형질 없음
  AND (GENOTYPE & 5) > 0;  -- 1번 또는 3번 형질 보유 (1 + 4 = 5)

/*
 * [자주 하는 실수]
 * - 형질 번호를 그대로 더함: 1 + 3 = 4로 마스크를 만들면 3번 형질만 검사하게 된다.
 *   반드시 자리 값(1, 2, 4, 8)으로 더해서 5를 써야 한다.
 * - 비교 연산 누락: WHERE GENOTYPE & 5 처럼 쓰면 MySQL에서는 돌아가지만 의도가 불분명하다.
 *   (GENOTYPE & 5) > 0 처럼 명시적으로 비교하는 습관을 들이자.
 * - 2번 조건을 반대로 씀: 2번이 "없어야" 하므로 = 0 이다. > 0 으로 쓰면 2번 보유자를 세게 된다.
 * - 괄호 누락: &는 비교 연산자(=, >)보다 우선순위가 낮아 보일 수 있으므로
 *   (GENOTYPE & 2) = 0 처럼 괄호로 묶어 순서를 확실히 한다.
 * - 1번 또는 3번 조건에 OR로 풀어쓰다 괄호 누락: 나눠 쓸 경우
 *   (GENOTYPE & 1) > 0 OR (GENOTYPE & 4) > 0 전체를 괄호로 한 번 더 묶어야 AND와 섞여도 안전하다.
 * - 컬럼명 누락: 출력 컬럼명이 COUNT여야 하므로 COUNT(*) AS COUNT를 꼭 붙인다.
 */