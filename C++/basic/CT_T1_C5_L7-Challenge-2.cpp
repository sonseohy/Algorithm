// A/B 출력 (Hard) - 코드트리 Trail1 Chapter5 Lesson7
// 두 정수 A, B를 입력받아 A/B의 값을 소수점 21번째 자리에서 내림하여 출력한다.
// 제한 조건: 1 <= A, B <= 100
// 힌트 : 20번째 자리까지 format을 이용하여 한 번에 출력하는 것은 쉽지 않다.

#include <iostream>

using namespace std;

int main() {
    int a, b;
    cin >> a >> b;

    // 정수부 출력 후 소수점 찍기
    cout << a / b << ".";

    // 나머지를 이용해 소수점 이하를 한 자리씩 계산 (긴 나눗셈)
    int r = a % b;

    int i = 0;
    while (i < 20) {
        r *= 10;           // 나머지에 10을 곱해 다음 자리 계산
        cout << r / b;     // 몫이 해당 소수 자리의 숫자
        r %= b;            // 나머지를 갱신
        i++;
    }

    return 0;
}

/*
[풀이] 수학에서의 소수점 구하는 연산
핵심: a/b의 나머지에 10을 곱해 b로 나눈 몫을 순서대로 적는 것을 반복한다.

예) 1 / 7 = 0.142857...
  1 * 10 / 7 = 1, 나머지 3
  3 * 10 / 7 = 4, 나머지 2
  2 * 10 / 7 = 2, 나머지 6
  6 * 10 / 7 = 8, 나머지 4 ...

이 과정을 20번 반복하면 소수점 20자리까지 얻어지고, 21번째 자리는 계산하지 않으므로 자연스럽게 내림된다.

시간 복잡도: O(1) / 공간 복잡도: O(1)
*/
